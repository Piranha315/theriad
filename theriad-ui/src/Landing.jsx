function formatModelSlug(slug) {
  const label = slug.split('/').pop()?.replace(/:free$/, '') || slug;
  return label
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, character => character.toUpperCase());
}

function getModelMeta(model) {
  return MODELS[model] || MODEL_META_BY_SLUG[model] || {
    name: formatModelSlug(model),
    short: formatModelSlug(model).slice(0, 2),
    color: '#9b7cff',
    img: null,
  };
}

