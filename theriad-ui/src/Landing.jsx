function LiveComparison() {
  const reduce = usePrefersReducedMotion();
  const [status, setStatus] = useState('idle');
  const [progress, setProgress] = useState(0);
  const rafRef = useRef(0);
  const { prices, live } = usePricing();

  const finals = useMemo(
    () => ({
      theriad: costAt('theriad', 1, prices),
      sol: costAt('sol', 1, prices),
      opus: costAt('opus', 1, prices),
    }),
    [prices]
  );
  const relativeCost = benchmark => {
    const percentage = benchmark > 0 ? Math.round(((benchmark - finals.theriad) / benchmark) * 100) : 0;
    return `${Math.abs(percentage)}% ${percentage >= 0 ? 'less' : 'more'}`;
  };

  useEffect(() => () => cancelAnimationFrame(rafRef.current), []);

  function run() {
    cancelAnimationFrame(rafRef.current);
    if (reduce) {
      setProgress(1);
      setStatus('done');
      return;
    }
    setProgress(0);
    setStatus('running');
    const duration = 4600;
    const start = performance.now();
    const tick = now => {
      const frac = Math.min(1, (now - start) / duration);
      setProgress(frac);
      if (frac < 1) {
        rafRef.current = requestAnimationFrame(tick);
      } else {
        setStatus('done');
      }
    };
    rafRef.current = requestAnimationFrame(tick);
  }

  const activeStep =
    status === 'done'
      ? compareSteps.length - 1
      : status === 'running'
        ? Math.min(compareSteps.length - 1, Math.floor(progress * compareSteps.length))
        : -1;
  const stepNumber = Math.min(compareSteps.length, Math.floor(progress * compareSteps.length) + (status === 'running' ? 1 : 0));

  const frac = status === 'idle' ? 0 : progress;
  const costs = {
    theriad: costAt('theriad', frac, prices),
    sol: costAt('sol', frac, prices),
    opus: costAt('opus', frac, prices),
  };

  return (
    <div className={styles.compare}>
      <div className={styles.comparePrompt}>
        <div>
          <span className={styles.compareLabel}>Agent task</span>
          <p>{AGENT_TASK}</p>
        </div>
        <button
          type="button"
          className={styles.compareRun}
          onClick={run}
          disabled={status === 'running'}
        >
          {status === 'idle' ? (
            <>
              <Play size={18} weight="fill" aria-hidden="true" /> Replay cost run
            </>
          ) : status === 'running' ? (
            'Running'
          ) : (
            <>
              <ArrowClockwise size={18} weight="bold" aria-hidden="true" /> Replay cost run
            </>
          )}
        </button>
      </div>

      <div className={styles.compareLanes}>
        {compareLanes.map(lane => {
          const meta = MODELS[lane.key];
          const isTheriad = lane.key === 'theriad';
          const cheapest = status === 'done' && isTheriad && finals.theriad <= Math.min(finals.sol, finals.opus);
          return (
            <div
              key={lane.key}
              className={`${styles.compareLane} ${isTheriad ? styles.compareLaneLead : ''}`}
            >
              <div className={styles.compareLaneTop}>
                <ModelMark model={lane.key} size={34} />
                <div>
                  <strong>{meta.name}</strong>
                  <span>{lane.role}</span>
                </div>
                {cheapest && <span className={styles.compareBadge}>Cheapest</span>}
              </div>

              <div className={styles.compareTicker} data-lead={isTheriad ? 'true' : undefined}>
                {fmtUsd(costs[lane.key])}
              </div>

              <div className={styles.compareBar}>
                <span style={{ transform: `scaleX(${status === 'idle' ? 0 : progress})` }} />
              </div>

              {isTheriad ? (
                <div className={styles.compareRoute}>
                  {status === 'idle' && <p>Cached route uses the cheapest capable model per step.</p>}
                  {status === 'running' && activeStep >= 0 && (
                    <p>
                      <span>Step {stepNumber}/{compareSteps.length}</span>
                      {compareSteps[activeStep].label}
                      <span className={styles.compareRouteTo}>
                        <ModelMark model={compareSteps[activeStep].model} size={18} />
                        {MODELS[compareSteps[activeStep].model].name}
                      </span>
                    </p>
                  )}
                  {status === 'done' && (
                    <div className={styles.compareUsed}>
                      {theriadModels.map(m => (
                        <span key={m} className={styles.compareUsedChip}>
                          <ModelMark model={m} size={16} />
                          {MODELS[m].name}
                        </span>
                      ))}
                    </div>
                  )}
                </div>
              ) : (
                <div className={styles.compareRoute}>
                  <p>{status === 'idle' ? `Cached run: all ${compareSteps.length} steps on ${meta.name}.` : `All ${compareSteps.length} steps on ${meta.name}.`}</p>
                </div>
              )}

              <div className={styles.compareOutput}>
                <div className={styles.compareOutputHeader}>
                  <span>Cached response</span>
                  <span>{CACHED_OUTPUTS[lane.key].kind}</span>
                </div>
                <div className={styles.compareOutputBody}>
                  <p>
                    <span className={styles.compareOutputLabel}>Response</span>
                    {CACHED_OUTPUTS[lane.key].summary}
                  </p>
                  <p>
                    <span className={styles.compareOutputLabel}>Recommendation</span>
                    {CACHED_OUTPUTS[lane.key].recommendation}
                  </p>
                </div>
              </div>
            </div>
          );
        })}
      </div>

      <div className={styles.compareResult} data-state={status} aria-live="polite">
        {status === 'done' ? (
          <>
            <CheckCircle size={20} weight="fill" aria-hidden="true" />
            <div className={styles.compareResultCopy}>
              <p>
                The cached Theriad route prices at <strong>{fmtUsd(finals.theriad)}</strong> for the
                same job: <strong>{relativeCost(finals.sol)}</strong> than {MODELS.sol.name} and{' '}
                <strong>{relativeCost(finals.opus)}</strong> than {MODELS.opus.name}.
              </p>
              <p className={styles.estimateDisclaimer}>
                Cached response previews are shown above. This landing page makes no provider calls.
                Estimates show illustrative provider/model cost for planning only. OpenRouter
                applies its own rates and usage limits.{' '}
                {live
                  ? 'Pricing uses current OpenRouter catalog rates.'
                  : 'Pricing uses the last known catalog rates, which may be out of date.'}
              </p>
            </div>
          </>
        ) : (
          <p className={styles.compareDisclaimer}>
            A cached response preview is shown above each lane. Replay uses the stored route and
            does not call providers. Pricing uses{' '}
            {live ? 'current OpenRouter catalog rates' : 'the last known catalog rates'}; token
            counts are shared across all three.
          </p>
        )}
      </div>
    </div>
  );
}

