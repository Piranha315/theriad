"""
Measured calibration: the eval grid's output, read by the router at startup.

The problem this solves
-----------------------
Two sets of numbers decide every route Theriad makes:

  - ``quality_prior`` / ``quality_profile`` in :mod:`theriad.models.registry`
  - ``TIER_VALUE_OF_QUALITY`` in :mod:`theriad.models.unified`

Before this module, both were hand-authored constants. Six of thirteen priors
came from a published Artificial Analysis index; the rest — including four of
the five free-tier models that now carry most traffic — were judgement calls,
and every per-tier V was. That is defensible as a cold start and indefensible as
a resting state, but the only path from guess to measurement ran through a human
editing ``registry.py`` by hand after reading a report. Nobody does that twice.

So the grid writes here instead. ``calibration.json`` is generated by
``python -m theriad.eval.run calibrate --write`` and applied to the registry at
construction. Re-running the eval re-routes production; no source edit, no
transcription step, no drift between what was measured and what is deployed.

What is deliberately *not* here
-------------------------------
The file is absent from a fresh checkout, and that is the supported state. When
it is missing, empty, or malformed, :func:`load_calibration` returns an empty
calibration and every consumer falls back to the hand-authored constants —
exactly the behaviour that shipped before. A calibration file is an upgrade, not
a dependency, because the alternative is a router that cannot start until
someone has spent $13 on provider calls.

Provenance is mandatory, not decorative. Every applied profile stamps
``quality_profile_source`` with the grid's trial count and generation date, so a
score in the registry can always be traced to the measurement that produced it —
and a score that came from nowhere stays visibly sourceless.
"""
from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from pathlib import Path

from .tiers import ModelCandidate

logger = logging.getLogger(__name__)

CALIBRATION_PATH = Path(__file__).with_name("calibration.json")
"""Default location. Ships absent; written by the eval harness."""

SCHEMA_VERSION = 1


@dataclass(frozen=True)
class Calibration:
    """Measured router parameters, or an empty set of them.

    Fields:
        quality_profiles: model slug → {axis: [0,1]}. Applied over the
                          registry's ``quality_profile``, axis by axis, so a
                          partially-measured model keeps its hand-authored
                          aggregate on the axes the grid did not cover.
        value_of_quality: tier → V, the quality/price exchange rate that
                          minimised measured regret for that tier.
        ability:          model slug → Rasch ability on the logit scale, fitted
                          by ``theriad.eval.irt.fit_rasch``. Paired with a
                          predicted item difficulty this gives
                          ``P(model solves this request)``, which is what
                          quality-constrained routing selects on. Kept separate
                          from ``quality_profiles`` on purpose: those are
                          shrunk onto the registry's published [0,1] prior scale
                          and compress a 0.127 accuracy gap into 0.002, which is
                          why cost dominated selection and the router never
                          escalated. Ability is not rescaled and keeps the
                          spread (2.995 inside the premium tier).
        grid_trials:      Total graded trials behind the numbers. Reported in
                          provenance so a thin measurement is visibly thin.
        generated_at:     ISO date the calibration was produced.
        corpus_sources:   Benchmark names the corpus drew from.
    """

    quality_profiles: dict[str, dict[str, float]] = field(default_factory=dict)
    value_of_quality: dict[str, float] = field(default_factory=dict)
    ability: dict[str, float] = field(default_factory=dict)
    grid_trials: int = 0
    generated_at: str | None = None
    corpus_sources: list[str] = field(default_factory=list)

    # ── Construction ─────────────────────────────────────────────────────────

    @classmethod
    def empty(cls) -> "Calibration":
        return cls()

    @property
    def is_empty(self) -> bool:
        return (
            not self.quality_profiles
            and not self.value_of_quality
            and not self.ability
        )

    @classmethod
    def load(cls, path: Path | str = CALIBRATION_PATH) -> "Calibration":
        """Read a calibration file, or return an empty one.

        Never raises. A missing file is the normal cold-start case; a corrupt
        one is logged and ignored rather than fatal, because refusing to route
        at all is a strictly worse failure than routing on the priors that
        shipped in source.
        """
        p = Path(path)
        if not p.exists():
            return cls.empty()
        try:
            raw = json.loads(p.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            logger.warning("ignoring unreadable calibration at %s: %s", p, exc)
            return cls.empty()

        version = raw.get("schema_version")
        if version != SCHEMA_VERSION:
            logger.warning(
                "ignoring calibration at %s: schema_version %r, expected %r",
                p, version, SCHEMA_VERSION,
            )
            return cls.empty()

        try:
            return cls(
                quality_profiles={
                    model: {a: float(s) for a, s in axes.items()}
                    for model, axes in raw.get("quality_profiles", {}).items()
                },
                value_of_quality={
                    tier: float(v)
                    for tier, v in raw.get("value_of_quality", {}).items()
                },
                ability={
                    model: float(a)
                    for model, a in raw.get("ability", {}).items()
                },
                grid_trials=int(raw.get("grid_trials", 0)),
                generated_at=raw.get("generated_at"),
                corpus_sources=list(raw.get("corpus_sources", [])),
            )
        except (TypeError, ValueError, AttributeError) as exc:
            logger.warning("ignoring malformed calibration at %s: %s", p, exc)
            return cls.empty()

    def to_dict(self) -> dict:
        return {
            "schema_version": SCHEMA_VERSION,
            "generated_at": self.generated_at,
            "grid_trials": self.grid_trials,
            "corpus_sources": self.corpus_sources,
            "quality_profiles": self.quality_profiles,
            "value_of_quality": self.value_of_quality,
            "ability": self.ability,
        }

    def save(self, path: Path | str = CALIBRATION_PATH) -> None:
        Path(path).write_text(json.dumps(self.to_dict(), indent=2, sort_keys=True) + "\n")

    # ── Application ──────────────────────────────────────────────────────────

    @property
    def provenance(self) -> str:
        """Source string stamped onto every profile this calibration applies."""
        return (
            f"theriad_eval_grid:{self.generated_at or 'unknown'}"
            f":{self.grid_trials}_trials"
        )

    def apply_to(self, candidate: ModelCandidate) -> bool:
        """Merge measured axes into ``candidate`` in place. True if anything changed.

        Merges rather than replaces: an axis the grid measured overrides the
        registry, an axis it did not measure keeps whatever the registry had
        (usually nothing, so ``quality_for`` falls through to the scalar prior).
        Replacing wholesale would silently *delete* hand-authored axis scores
        that a narrow corpus happened not to cover.
        """
        measured = self.quality_profiles.get(candidate.model)
        if not measured:
            return False
        merged = dict(candidate.quality_profile or {})
        merged.update(measured)
        candidate.quality_profile = merged
        candidate.quality_profile_source = self.provenance
        return True

    def apply_to_tiers(self, tier_config: dict[str, list[ModelCandidate]]) -> int:
        """Apply to every candidate in a tier config. Returns candidates updated."""
        if self.is_empty:
            return 0
        return sum(
            1
            for candidates in tier_config.values()
            for c in candidates
            if self.apply_to(c)
        )


_cached: Calibration | None = None


def load_calibration(path: Path | str = CALIBRATION_PATH) -> Calibration:
    """Process-wide cached load. Call :func:`reset_calibration_cache` in tests."""
    global _cached
    if _cached is None:
        _cached = Calibration.load(path)
    return _cached


def reset_calibration_cache() -> None:
    global _cached
    _cached = None
